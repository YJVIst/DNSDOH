CREATE TABLE admins (
 id VARCHAR(36) PRIMARY KEY, username VARCHAR(80) NOT NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL, created_at BIGINT NOT NULL
) ENGINE=InnoDB;
CREATE TABLE sessions (
 token_hash CHAR(64) PRIMARY KEY, admin_id VARCHAR(36) NOT NULL, csrf VARCHAR(80) NOT NULL,
 expires_at BIGINT NOT NULL, FOREIGN KEY (admin_id) REFERENCES admins(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE users (
 id VARCHAR(36) PRIMARY KEY, name VARCHAR(100) NOT NULL, note VARCHAR(500) NOT NULL DEFAULT '',
 enabled BOOLEAN NOT NULL DEFAULT TRUE, expires_at BIGINT NULL, created_at BIGINT NOT NULL
) ENGINE=InnoDB;
CREATE TABLE zones (
 id VARCHAR(36) PRIMARY KEY, name VARCHAR(253) NOT NULL UNIQUE,
 note VARCHAR(500) NOT NULL DEFAULT '', enabled BOOLEAN NOT NULL DEFAULT TRUE, created_at BIGINT NOT NULL
) ENGINE=InnoDB;
CREATE TABLE records (
 id VARCHAR(36) PRIMARY KEY, zone_id VARCHAR(36) NOT NULL, name VARCHAR(253) NOT NULL,
 record_type VARCHAR(8) NOT NULL, value VARCHAR(64) NOT NULL, ttl INT NOT NULL DEFAULT 60,
 enabled BOOLEAN NOT NULL DEFAULT TRUE, created_at BIGINT NOT NULL,
 UNIQUE KEY record_unique(zone_id,name,record_type,value),
 FOREIGN KEY (zone_id) REFERENCES zones(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE user_zones (
 user_id VARCHAR(36) NOT NULL, zone_id VARCHAR(36) NOT NULL, PRIMARY KEY(user_id,zone_id),
 FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE,
 FOREIGN KEY(zone_id) REFERENCES zones(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE tokens (
 id VARCHAR(36) PRIMARY KEY, user_id VARCHAR(36) NOT NULL, name VARCHAR(100) NOT NULL,
 token_hash CHAR(64) NOT NULL UNIQUE, prefix VARCHAR(16) NOT NULL,
 enabled BOOLEAN NOT NULL DEFAULT TRUE, expires_at BIGINT NULL, created_at BIGINT NOT NULL,
 FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE nodes (
 id VARCHAR(36) PRIMARY KEY, name VARCHAR(100) NOT NULL, endpoint VARCHAR(400) NOT NULL UNIQUE,
 region VARCHAR(80) NOT NULL DEFAULT '', note VARCHAR(500) NOT NULL DEFAULT '',
 secret_hash CHAR(64) NOT NULL, enabled BOOLEAN NOT NULL DEFAULT TRUE,
 last_seen BIGINT NULL, applied_revision BIGINT NOT NULL DEFAULT 0,
 version VARCHAR(40) NOT NULL DEFAULT '', created_at BIGINT NOT NULL
) ENGINE=InnoDB;
CREATE TABLE settings (
 id INT PRIMARY KEY, revision BIGINT NOT NULL DEFAULT 1,
 token_qps INT NOT NULL DEFAULT 30, retention_days INT NOT NULL DEFAULT 14
) ENGINE=InnoDB;
