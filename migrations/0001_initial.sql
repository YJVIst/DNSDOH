CREATE TABLE audit_events (
 id BIGINT AUTO_INCREMENT PRIMARY KEY, actor VARCHAR(100) NOT NULL,
 action VARCHAR(80) NOT NULL, target VARCHAR(253) NOT NULL, created_at BIGINT NOT NULL,
 INDEX audit_created(created_at)
) ENGINE=InnoDB;
CREATE TABLE metric_reports (
 report_id VARCHAR(36) PRIMARY KEY, node_id VARCHAR(36) NOT NULL, created_at BIGINT NOT NULL
) ENGINE=InnoDB;
CREATE TABLE metrics (
 node_id VARCHAR(36) NOT NULL, bucket BIGINT NOT NULL,
 total BIGINT NOT NULL DEFAULT 0, success BIGINT NOT NULL DEFAULT 0,
 denied BIGINT NOT NULL DEFAULT 0, errors BIGINT NOT NULL DEFAULT 0,
 latency_us BIGINT NOT NULL DEFAULT 0, PRIMARY KEY(node_id,bucket)
) ENGINE=InnoDB;
